import pytest

from numword_georgia import translate


@pytest.mark.parametrize(
    ("number", "expected"),
    [
        (0, "ნული"),
        (16, "თექვსმეტი"),
        (-16, "მინუსი თექვსმეტი"),
        (20, "ოცი"),
        (21, "ოცდაერთი"),
        (30, "ოცდაათი"),
        (38, "ოცდათვრამეტი"),
        (47, "ორმოცდაშვიდი"),
        (80, "ოთხმოცი"),
        (99, "ოთხმოცდაცხრამეტი"),
        (120, "ას ოცი"),
        (250, "ორას ორმოცდაათი"),
        (415, "ოთხას თხუთმეტი"),
        (1000, "ათასი"),
        (1001, "ათას ერთი"),
        (1200, "ათას ორასი"),
        (1999, "ათას ცხრაას ოთხმოცდაცხრამეტი"),
        (2000, "ორი ათასი"),
        (2010, "ორი ათას ათი"),
        (5909, "ხუთი ათას ცხრაას ცხრაი"),
        # WARNING: this test may be wrong, in Babel first word is `ცხრა` w/o `ი`
        (9999, "ცხრაი ათას ცხრაას ოთხმოცდაცხრამეტი"),
        (10000, "ათი ათასი"),
        (10001, "ათი ათას ერთი"),
        (1000000, "ერთი მილიონი"),
        (1000001, "ერთი მილიონ ერთი"),
        (99000000, "ოთხმოცდაცხრამეტი მილიონი"),
        (999999999, "ცხრაას ოთხმოცდაცხრამეტი მილიონ ცხრაას ოთხმოცდაცხრამეტი ათას ცხრაას ოთხმოცდაცხრამეტი"),
    ],
)
def test_translate(number: int, expected: str) -> None:
    assert translate(number) == expected
